"""Render the Section 7 event table from the saved simulation results."""

import argparse

from .run_part7 import DATA, GOAL_EVENTS, case_id, read_json


def render_table(result):
    config, cases = result['config'], result['cases']
    nominal = config['reference_e_n']
    mu_f = config['ablation_mu_f']
    near_friction = case_id('near', 'air', nominal, mu_f)
    rows = [('Low, gravity', case_id('low', 'gravity', nominal))]
    rows.extend(('Low, still air', case_id('low', 'air', e_n, 0))
                for e_n in config['restitution'])
    rows.extend([
        ('Near, still air', case_id('near', 'air', nominal, 0)),
        ('Near, still air', case_id('near', 'air', nominal, .1)),
        ('Near, still air', near_friction),
        ('Near, no post-impact lift', f'{near_friction}/no_lift'),
    ])
    lines = [r'''% Generated by scripts/part07/write_part7_table.py.
\begin{table}[!htbp]
\centering
\caption{First impact and terminal events for selected synthetic shots.
The low and near launches have \(v_{0z}=1.0\) and \(1.8\,\mathrm{m\,s^{-1}}\),
respectively. All times are from release. Contact denotes the second
ground contact.}
\label{tab:part7-events}
\small
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}lrrrcrrl@{}}
\toprule
Case & \(e_n\) & \(\mu_f\) & \(t_1\) (s) &
\((v_z^-,v_z^+)\) (m/s) & \(t_{\rm end}\) (s) & \(x_{\rm end}\) (m) & Event \\
\midrule''']
    for name, key in rows:
        row = cases[key]
        impact = row['impact']
        if row['event'] in GOAL_EVENTS:
            event = 'Inside goal' if row['event'] == 'goal_inside' else 'Outside goal'
        elif row['event'] == 'second_ground':
            event = 'Contact'
        else:
            raise ValueError(f'Unexpected event in paper table: {row["event"]}')
        lines.append(
            rf'{name} & {row["e_n"]:.1f} & {row["mu_f"]:.2f} & {impact["time"]:.4f} & '
            rf'\(({impact["v_minus"][2]:.3f}, {impact["v_plus"][2]:+.3f})\) & '
            rf'{row["time_s"]:.4f} & {row["state"][0]:.2f} & {event} \\'
        )
    lines.append(r'''\bottomrule
\end{tabular}
\end{table}''')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check the exported table.')
    options = parser.parse_args()
    path = DATA / 'bounce_event_table.tex'
    table = render_table(read_json(DATA / 'results.json')) + '\n'
    if options.check:
        if not path.is_file() or path.read_text(encoding='utf-8') != table:
            raise SystemExit('Section 7 event table is out of date.')
    else:
        path.write_text(table, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
